// About + first-run onboarding: how to play (with the ghost-hand demo), the heritage
// badge, credits and the story link.
import { Dialog } from "radix-ui";
import { useEffect, useRef } from "react";
import { track } from "../../lib/analytics.ts";
import { openSheet, useUi } from "../../state/ui.ts";
import { KEYS, writeString } from "../../lib/storage.ts";
import { GhostDemo } from "../../components/GhostDemo.tsx";
import { ExternalIcon, LogoMark } from "../../components/Icons.tsx";
import { LEARN_MORE_URL, LITTLE_ALCHEMY_URL, ORIGIN_BADGE, ORIGIN_BADGE_TITLE } from "../../content.ts";
import { Sheet } from "./Sheet.tsx";
import { DEMO_RECIPE } from "../../../shared/starters.ts";

const STEPS: { title: string; body: string }[] = [
  { title: "Drag one element onto another", body: `${DEMO_RECIPE.a} + ${DEMO_RECIPE.b}? The AI decides what you made, and paints it.` },
  { title: "Or just tap", body: "Tap an element to select it, then tap another to combine. No dragging needed." },
  { title: "Mix up to four", body: "Hold your element over a second one for a moment to gather it, then drop on a third." },
  { title: "Be first", body: "Make something nobody has ever made and it's yours forever, with a gold seal." },
];

export function HeritageBadge() {
  return (
    <span
      title={ORIGIN_BADGE_TITLE}
      className="inline-flex items-center gap-1.5 rounded-full border border-[color-mix(in_oklab,var(--gold-3)_45%,var(--border))] bg-[color-mix(in_oklab,var(--gold-1)_16%,var(--surface))] px-3 py-1 text-[12px] font-semibold text-gold">
      <svg width="10" height="10" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
        <path d="M12 2.5c.5 4.6 2.4 7 7 7.5-4.6.5-6.5 2.9-7 7.5-.5-4.6-2.4-7-7-7.5 4.6-.5 6.5-2.9 7-7.5Z" />
      </svg>
      {ORIGIN_BADGE}
    </span>
  );
}

export default function AboutSheet({ open }: { open: boolean }) {
  const onboarding = useUi((s) => s.onboarding);
  // Onboarding funnel (analytics only): when the welcome sheet appeared and how it was left.
  const shownAt = useRef(0);
  const closeVia = useRef<"start" | "dismiss">("dismiss");
  useEffect(() => {
    if (!open || !onboarding) return;
    shownAt.current = Date.now();
    closeVia.current = "dismiss";
    track("onboarding", { action: "shown" });
  }, [open, onboarding]);
  /** Whole seconds the welcome sheet has been open, capped at 10 minutes. */
  const secs = () => Math.min(600, Math.round((Date.now() - shownAt.current) / 1000));
  const onLink = (target: string) => () => {
    if (onboarding) track("onboarding", { action: "link", target, secs: secs() });
  };
  const close = () => {
    if (onboarding) track("onboarding", { action: closeVia.current, secs: secs() });
    writeString(KEYS.onboarded, "1");
    useUi.setState({ onboarding: false });
    openSheet(null);
  };
  const title = onboarding ? "Welcome, alchemist" : "Infinite Alchemy";
  return (
    <Sheet
      open={open}
      onOpenChange={(o) => !o && close()}
      title={
        <span className="flex items-center gap-2">
          <LogoMark size={26} />
          {title}
        </span>
      }
      description="How to play Infinite Alchemy."
      testId={onboarding ? "onboarding" : "about-sheet"}
    >
      <HeritageBadge />
      <p className="mt-3 text-[15px]">Start with five elements. Combine them into anything at all: steam, a volcano, Isaac Newton, a time machine.</p>
      <GhostDemo className="mt-4" />
      <ol className="mt-4 flex flex-col gap-3">
        {STEPS.map((s, i) => (
          <li key={s.title} className="flex gap-3">
            <span className="font-display grid h-7 w-7 flex-none place-items-center rounded-full bg-accent-soft text-[14px] font-semibold text-accent">{i + 1}</span>
            <span>
              <span className="block font-semibold">{s.title}</span>
              <span className="block text-[14px] text-ink-muted">{s.body}</span>
            </span>
          </li>
        ))}
      </ol>
      <p className="mt-4 text-[13px] text-ink-muted">
        Inspired by{" "}
        <a className="font-semibold text-accent underline-offset-2 hover:underline" href={LITTLE_ALCHEMY_URL} target="_blank" rel="noopener" onClick={onLink("little_alchemy")}>
          Little Alchemy
        </a>
        . Elements, recipes and art are generated by AI, so the possibilities are infinite.{" "}
        <a className="inline-flex items-center gap-0.5 font-semibold text-accent underline-offset-2 hover:underline" href={LEARN_MORE_URL} target="_blank" rel="noopener" onClick={onLink("learn_more")}>
          Learn more <ExternalIcon size={13} />
        </a>
      </p>
      <nav aria-label="Guides" className="mt-3 flex flex-wrap gap-x-4 gap-y-1 text-[14px]">
        <a className="font-semibold text-accent underline-offset-2 hover:underline" href="/how-to-play" onClick={onLink("how_to_play")}>How to play</a>
        <a className="font-semibold text-accent underline-offset-2 hover:underline" href="/daily" onClick={onLink("daily")}>Today's challenge</a>
        <a className="font-semibold text-accent underline-offset-2 hover:underline" href="/recipes" onClick={onLink("recipes")}>Recipes</a>
        <a className="font-semibold text-accent underline-offset-2 hover:underline" href="/about" onClick={onLink("about")}>About</a>
      </nav>
      <Dialog.Close asChild>
        <button
          type="button"
          className="btn btn-primary mt-5 w-full"
          data-testid={onboarding ? "onboarding-dismiss" : undefined}
          // Runs before Dialog.Close closes the sheet, so close() reports "start", not "dismiss".
          onClick={() => (closeVia.current = "start")}
        >
          {onboarding ? "Start mixing" : "Back to the workbench"}
        </button>
      </Dialog.Close>
    </Sheet>
  );
}
